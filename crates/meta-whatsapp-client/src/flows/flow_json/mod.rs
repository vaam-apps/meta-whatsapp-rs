/// A Flow JSON document (`flows/guides/flowjson`, § Top-level Flow JSON
/// properties). Parse one with `serde_json`, or build one with
/// [`FlowJson::builder`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FlowJson {
    /// `version`: the Flow JSON version, `{major}.{minor}` (see Meta's
    /// changelog for the ones it accepts).
    pub version: String,
    /// `data_api_version`: set when the Flow uses a data endpoint.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub data_api_version: Option<String>,
    /// `routing_model`: screen id to the screens it may lead to. Required
    /// with a data endpoint; generated by Meta otherwise.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub routing_model: Option<BTreeMap<String, Vec<String>>>,
    /// `data_channel_uri`: the data endpoint's URL, before Flow JSON 3.0
    /// only (from 3.0 it is the Flow's `endpoint_uri`, set through the API).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub data_channel_uri: Option<String>,
    /// `screens`.
    pub screens: Vec<Screen>,
    /// Properties this version does not model, kept as sent.
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl FlowJson {
    /// A document of Flow JSON `version` with no screens yet.
    pub fn new(version: impl Into<String>) -> Self {
        Self {
            version: version.into(),
            data_api_version: None,
            routing_model: None,
            data_channel_uri: None,
            screens: Vec::new(),
            extra: Map::new(),
        }
    }

    /// A builder for a document of Flow JSON `version`.
    pub fn builder(version: impl Into<String>) -> FlowJsonBuilder {
        FlowJsonBuilder {
            flow: Self::new(version),
        }
    }

    /// Check the limits the docs give (see the module docs); the first
    /// problem found is returned, its `field` a path from the document's
    /// root (`screens[0].layout.children[1].label`).
    pub fn validate(&self) -> Result<(), ValidationError> {
        validate::flow(self)
    }

    /// The screen with `id`.
    pub fn screen(&self, id: &str) -> Option<&Screen> {
        self.screens.iter().find(|s| s.id == id)
    }

    /// The document as compact JSON text, without validating it.
    pub fn to_json_string(&self) -> Result<String, ValidationError> {
        serde_json::to_string(self)
            .map_err(|e| ValidationError::new("flow_json", format!("not serializable: {e}")))
    }
}

/// Builds a [`FlowJson`]; [`Self::build`] validates it.
#[derive(Debug, Clone, PartialEq)]
pub struct FlowJsonBuilder {
    flow: FlowJson,
}

impl FlowJsonBuilder {
    /// Set `data_api_version` (the Flow uses a data endpoint; it then
    /// needs a routing model, see [`Self::route`]).
    #[must_use]
    pub fn data_api_version(mut self, version: impl Into<String>) -> Self {
        self.flow.data_api_version = Some(version.into());
        self
    }

    /// Set `data_channel_uri` (Flow JSON before 3.0 only).
    #[must_use]
    pub fn data_channel_uri(mut self, uri: impl Into<String>) -> Self {
        self.flow.data_channel_uri = Some(uri.into());
        self
    }

    /// Add a route: `from` may lead to each of `to` (an empty `to` marks a
    /// screen with no forward route).
    #[must_use]
    pub fn route<I, S>(mut self, from: impl Into<String>, to: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.flow
            .routing_model
            .get_or_insert_with(BTreeMap::new)
            .entry(from.into())
            .or_default()
            .extend(to.into_iter().map(Into::into));
        self
    }

    /// Add a screen.
    #[must_use]
    pub fn screen(mut self, screen: Screen) -> Self {
        self.flow.screens.push(screen);
        self
    }

    /// Set a top-level property this version does not model.
    #[must_use]
    pub fn extra(mut self, key: impl Into<String>, value: impl Into<Value>) -> Self {
        self.flow.extra.insert(key.into(), value.into());
        self
    }

    /// The document, once [`FlowJson::validate`] accepts it.
    pub fn build(self) -> Result<FlowJson, ValidationError> {
        self.flow.validate()?;
        Ok(self.flow)
    }

    /// The document as it stands, unchecked.
    pub fn build_unchecked(self) -> FlowJson {
        self.flow
    }
}

/// One screen (`flows/guides/flowjson`, § Screens). Build it with
/// [`Screen::new`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Screen {
    /// `id`: unique in the Flow; letters and underscores; not `SUCCESS`.
    pub id: String,
    /// `title`: shown in the top bar.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    /// `terminal`: the Flow may end here (such a screen needs a `Footer`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub terminal: Option<bool>,
    /// `success` (terminal screens only, default true): whether ending here
    /// is a successful outcome.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub success: Option<bool>,
    /// `data`: the screen's data model, field name to declaration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub data: Option<BTreeMap<String, DataField>>,
    /// `refresh_on_back` (Flows with a data endpoint only, default false):
    /// ask the endpoint again when the user comes back to this screen.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub refresh_on_back: Option<bool>,
    /// `sensitive` (Flow JSON 5.1+): names of fields masked in the summary
    /// the user sees once the Flow completes.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sensitive: Option<Vec<String>>,
    /// `layout`.
    pub layout: Layout,
    /// Properties this version does not model, kept as sent.
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl Screen {
    /// A screen `id` with an empty `SingleColumnLayout`.
    pub fn new(id: impl Into<String>) -> Self {
        Self {
            id: id.into(),
            title: None,
            terminal: None,
            success: None,
            data: None,
            refresh_on_back: None,
            sensitive: None,
            layout: Layout::single_column(),
            extra: Map::new(),
        }
    }

    /// Set `title`.
    #[must_use]
    pub fn title(mut self, title: impl Into<String>) -> Self {
        self.title = Some(title.into());
        self
    }

    /// Set `terminal`.
    #[must_use]
    pub fn terminal(mut self, terminal: bool) -> Self {
        self.terminal = Some(terminal);
        self
    }

    /// Set `success`.
    #[must_use]
    pub fn success(mut self, success: bool) -> Self {
        self.success = Some(success);
        self
    }

    /// Declare the data field `name`.
    #[must_use]
    pub fn data_field(mut self, name: impl Into<String>, field: DataField) -> Self {
        self.data
            .get_or_insert_with(BTreeMap::new)
            .insert(name.into(), field);
        self
    }

    /// Set an empty data model (`"data": {}`).
    #[must_use]
    pub fn empty_data(mut self) -> Self {
        self.data.get_or_insert_with(BTreeMap::new);
        self
    }

    /// Set `refresh_on_back`.
    #[must_use]
    pub fn refresh_on_back(mut self, refresh: bool) -> Self {
        self.refresh_on_back = Some(refresh);
        self
    }

    /// Set `sensitive`.
    #[must_use]
    pub fn sensitive<I, S>(mut self, fields: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.sensitive = Some(fields.into_iter().map(Into::into).collect());
        self
    }

    /// Append a component to the layout.
    #[must_use]
    pub fn child(mut self, component: impl Into<Component>) -> Self {
        self.layout.children.push(component.into());
        self
    }

    /// Replace the layout.
    #[must_use]
    pub fn layout(mut self, layout: Layout) -> Self {
        self.layout = layout;
        self
    }

    /// Set a property this version does not model.
    #[must_use]
    pub fn extra(mut self, key: impl Into<String>, value: impl Into<Value>) -> Self {
        self.extra.insert(key.into(), value.into());
        self
    }
}

wire_enum! {
    /// A layout's `type`.
    pub enum LayoutType {
        /// `SingleColumnLayout`: a vertical stack, the only layout so far.
        SingleColumnLayout = "SingleColumnLayout",
    }
}

/// A screen's `layout` (`flows/guides/flowjson`, § Layout).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Layout {
    /// `type`.
    #[serde(rename = "type")]
    pub kind: LayoutType,
    /// `children`: the components, top to bottom (at most 50).
    pub children: Vec<Component>,
    /// Properties this version does not model, kept as sent.
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl Layout {
    /// An empty `SingleColumnLayout`.
    pub fn single_column() -> Self {
        Self {
            kind: LayoutType::SingleColumnLayout,
            children: Vec::new(),
            extra: Map::new(),
        }
    }
}

wire_enum! {
    /// A data field's `type` (JSON Schema types; Flows check them per RFC
    /// 8927 and do not support `null`).
    pub enum DataType {
        /// `string`.
        String = "string",
        /// `number`.
        Number = "number",
        /// `boolean`.
        Boolean = "boolean",
        /// `object`.
        Object = "object",
        /// `array`.
        Array = "array",
    }
}

/// An array's `items`: a schema, or a boolean (the error codes allow both).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum DataItems {
    /// The schema of each item.
    Schema(Box<DataField>),
    /// `true` or `false`.
    Bool(bool),
}

/// The declaration of one field of a screen's `data` (a JSON Schema
/// subset, `flows/guides/flowjson` § Declaring screen properties).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DataField {
    /// `type`.
    #[serde(rename = "type", default, skip_serializing_if = "Option::is_none")]
    pub kind: Option<DataType>,
    /// `items` (arrays).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub items: Option<DataItems>,
    /// `properties` (objects).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub properties: Option<BTreeMap<String, DataField>>,
    /// `__example__`: mock data for previews, required on top-level fields
    /// (and allowed only there).
    #[serde(
        rename = "__example__",
        default,
        skip_serializing_if = "Option::is_none"
    )]
    pub example: Option<Value>,
    /// Properties this version does not model, kept as sent.
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl DataField {
    /// A field of `type` `kind`.
    pub fn of(kind: DataType) -> Self {
        Self {
            kind: Some(kind),
            items: None,
            properties: None,
            example: None,
            extra: Map::new(),
        }
    }

    /// A `string`.
    pub fn string() -> Self {
        Self::of(DataType::String)
    }

    /// A `number`.
    pub fn number() -> Self {
        Self::of(DataType::Number)
    }

    /// A `boolean`.
    pub fn boolean() -> Self {
        Self::of(DataType::Boolean)
    }

    /// An `object` with `properties`.
    pub fn object<I, S>(properties: I) -> Self
    where
        I: IntoIterator<Item = (S, DataField)>,
        S: Into<String>,
    {
        let mut field = Self::of(DataType::Object);
        field.properties = Some(
            properties
                .into_iter()
                .map(|(name, f)| (name.into(), f))
                .collect(),
        );
        field
    }

    /// An `array` of `items`.
    pub fn array(items: DataField) -> Self {
        let mut field = Self::of(DataType::Array);
        field.items = Some(DataItems::Schema(Box::new(items)));
        field
    }

    /// Set `__example__`.
    #[must_use]
    pub fn example(mut self, example: impl Into<Value>) -> Self {
        self.example = Some(example.into());
        self
    }
}
