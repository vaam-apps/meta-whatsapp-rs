//! A typed model of Flow JSON, with a builder that checks the documented
//! limits locally (`flows/guides/flowjson`, `flows/guides/components`,
//! `flows/guides/media_upload`, the static validation errors of
//! `flows/reference/error-codes`).
//!
//! [`FlowJson`] is the document; its [`Screen`]s each hold a [`Layout`] of
//! [`Component`]s, a tagged enum by `type`; [`Action`]s are tagged by
//! `name`. Properties that may be bound to data are a [`Dynamic<T>`] (or a
//! plain `String`, which holds a reference such as `${data.title}` as its
//! value).
//!
//! The model is lossless for what it parses: every struct keeps the
//! properties it does not model in a flattened `extra` map, and an unknown
//! component or action is kept whole (`Unknown { raw }`), so parsing a Flow
//! JSON and serializing it gives back the same JSON value (key order
//! aside). A property of the wrong type fails parsing instead of being
//! dropped.
//!
//! # Build a Flow
//!
//! ```
//! use meta_whatsapp_client::flows::flow_json::{
//!     Action, Footer, FlowJson, Screen, TextHeading,
//! };
//!
//! let flow = FlowJson::builder("7.3")
//!     .screen(
//!         Screen::new("WELCOME_SCREEN")
//!             .title("Welcome")
//!             .terminal(true)
//!             .success(true)
//!             .child(TextHeading::new("Hello World"))
//!             .child(Footer::new("Complete", Action::complete())),
//!     )
//!     .build()?; // checks the documented limits
//! assert_eq!(flow.screens[0].layout.children.len(), 2);
//! # Ok::<(), meta_whatsapp_core::error::ValidationError>(())
//! ```
//!
//! Send it with [`CreateFlow::flow_json_typed`](super::CreateFlow::flow_json_typed)
//! or [`Flow::upload_flow_json_typed`](super::Flow::upload_flow_json_typed);
//! both validate first. To send one the local checks refuse (they follow
//! the docs, and Meta's validator is the authority), serialize it with
//! [`FlowJson::to_json_string`] and use the raw-JSON calls.
//!
//! # Edit an existing Flow JSON
//!
//! ```
//! use meta_whatsapp_client::flows::flow_json::{Component, FlowJson};
//!
//! let text = r#"{"version":"7.3","screens":[{"id":"A","terminal":true,"layout":{
//!   "type":"SingleColumnLayout","children":[{"type":"NewWidget","size":3},
//!   {"type":"Footer","label":"Done","on-click-action":{"name":"complete","payload":{}}}]}}]}"#;
//! let mut flow: FlowJson = serde_json::from_str(text)?;
//! assert!(matches!(flow.screens[0].layout.children[0], Component::Unknown { .. }));
//! flow.screens[0].title = Some("Hello".into());
//! let back = serde_json::to_value(&flow)?;
//! assert_eq!(back["screens"][0]["layout"]["children"][0]["size"], 3);
//! # Ok::<(), serde_json::Error>(())
//! ```

